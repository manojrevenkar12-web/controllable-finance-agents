"""Choose the confidence above which coded documents are offered for bulk approval, on dev only.

Runs the pattern coder (no model calls, no writes) over the dev month, pairs each document's confidence with
whether every line was right, and picks the lowest threshold whose documents are right at least as often as
the target says. The result goes to config/thresholds.yaml with how it was chosen.
"""

from __future__ import annotations

import datetime as dt
import json

import yaml

from .. import config
from ..agents.client import Ledger
from ..agents.coding import CompanyModel, DocumentCoding
from ..ledger.app import reset_pool
from ..ledger.auth import mint
from ..ledger.seed import seed


def rows(split: str) -> list[tuple[float, bool]]:
    month = config.load("world")["months"]["splits"][split]
    reset_pool()
    seed(split)
    reset_pool()
    truth = json.loads((config.DATA / split / "truth.json").read_text())["documents"]
    out = []
    for t in [x["id"] for x in config.load("world")["tenants"]]:
        led = Ledger.in_process(mint("agent:calibrate", t, "agent"))
        ref = led.reference()
        model = CompanyModel(led.bookings(), led.people(), ref["cost_centres"])
        for d in led.documents(month):
            dc = DocumentCoding(d["id"], [model.code_line(d, i, x) for i, x in enumerate(d["lines"])])
            if not dc.complete:
                continue
            right = all(
                x.account == y["account"] and x.cost_centre == y["cost_centre"] and x.tax_key == y["tax_key"]
                for x, y in zip(dc.lines, truth[d["id"]]["coding"], strict=True)
            )
            out.append((dc.confidence, right))
    return out


def choose(data: list[tuple[float, bool]], target: float, minimum: int) -> dict:
    best = None
    for thr in sorted({round(c, 4) for c, _ in data}):
        sel = [ok for c, ok in data if c >= thr]
        if len(sel) < minimum:
            break
        prec = sum(sel) / len(sel)
        if prec >= target:
            best = {
                "ready_confidence": thr,
                "precision": round(prec, 4),
                "documents": len(sel),
                "coverage": round(len(sel) / len(data), 4),
            }
            break
    return best or {"ready_confidence": 1.01, "precision": None, "documents": 0, "coverage": 0.0}


def calibrate() -> dict:
    cfg = config.load("gates")["calibration"]
    data = rows(cfg["split"])
    best = choose(data, cfg["ready_precision_target"], cfg["min_ready_documents"])
    out = {
        "ready_confidence": best["ready_confidence"],
        "chosen_on": {
            "split": cfg["split"],
            "target_precision": cfg["ready_precision_target"],
            "precision": best["precision"],
            "ready_documents": best["documents"],
            "coverage": best["coverage"],
            "documents": len(data),
            "agent_version": config.load("agents")["coding"]["version"],
            "date": dt.date.today().isoformat(),
        },
    }
    (config.ROOT / "config" / "thresholds.yaml").write_text(
        "# Generated by `cfa calibrate` on the dev split; do not edit by hand, and never calibrate on test.\n"
        + yaml.safe_dump(out, sort_keys=False)
    )
    return out
